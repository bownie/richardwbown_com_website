#!/usr/bin/env node
// Generates public/_redirects from the redirect maps in astro.config.mjs.
//
// Astro's own `redirects` option can only produce meta-refresh HTML for a
// static build. Cloudflare Workers, Cloudflare Pages and Netlify read this
// file instead and answer with real 301s, so both outputs come from the same
// maps and cannot drift apart.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { hostRedirects, redirectDestinations } from "../astro.config.mjs";

const outFile = fileURLToPath(new URL("../public/_redirects", import.meta.url));

const rules = [
  ...Object.entries(redirectDestinations),
  ...Object.entries(hostRedirects)
];

const sources = new Set();
for (const [from] of rules) {
  if (sources.has(from)) {
    throw new Error(
      `Duplicate redirect source ${from}: it is defined in both redirectDestinations and hostRedirects.`
    );
  }
  sources.add(from);
}

// Exact rules go before splats. The host applies the first rule that matches,
// so /tag/* must not swallow an exact path that deserves its own destination.
const isSplat = (from) => from.includes("*");
rules.sort(
  ([a], [b]) =>
    Number(isSplat(a)) - Number(isSplat(b)) || a.localeCompare(b)
);

const header = [
  "# Generated by scripts/build-redirects.mjs from the redirect maps in",
  "# astro.config.mjs. Do not edit by hand: run `npm run redirects`.",
  "#",
  "# Cloudflare Workers/Pages and Netlify read this file and answer with real",
  "# 301s. GitHub Pages ignores it; the Pages build gets its redirects from the",
  "# same maps, emitted as meta-refresh pages instead.",
  "#",
  "# /work-with-me/ is deliberately absent: it is a real page, not a redirect."
].join("\n");

const body = rules.map(([from, to]) => `${from} ${to} 301`).join("\n");
const contents = `${header}\n\n${body}\n`;

await writeFile(outFile, contents);
console.log(
  `Wrote ${rules.length} redirect rules to public/_redirects (${rules.filter(([from]) => isSplat(from)).length} splat).`
);
